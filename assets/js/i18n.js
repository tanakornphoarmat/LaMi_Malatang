// Current Active Language
let currentLang = localStorage.getItem('lamimalatang_lang') || 'th';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('lamimalatang_lang', lang);
    document.documentElement.lang = lang;

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key] !== undefined) {
            const val = translations[lang][key];
            if (val.includes('<') && val.includes('>')) {
                el.innerHTML = val;
            } else {
                el.textContent = val;
            }
        }
    });

    // Update input placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (translations[lang] && translations[lang][key] !== undefined) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    // Update active state on language toggle buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
}

// Make setLanguage globally available
window.setLanguage = setLanguage;

// Initial execution
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => setLanguage(currentLang));
} else {
    setLanguage(currentLang);
}

// Event listeners for language toggle buttons
document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) {
        e.preventDefault();
        const lang = btn.getAttribute('data-lang');
        setLanguage(lang);
    }
});
